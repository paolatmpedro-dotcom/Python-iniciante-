temperatura = input("Digite uma temperatura em Celsius: ")
temperatura = int(temperatura)

fahrenheit = (temperatura * 9 / 5) + 32

print("\nA temperatura em Celsius é: ", temperatura, "\nA temperatura convertida em Fahrenheit é",fahrenheit)
print(f"\nA temperatura em Celsius é:  {temperatura} \nA temperatura convertida em Fahrenheit é {fahrenheit}")
